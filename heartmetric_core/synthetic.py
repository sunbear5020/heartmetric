"""Synthetic 14-day cardiovascular + environmental exposure series.

Everything here is generated by this file with a fixed random seed. No vendor
sample file, no real participant, no scraped value is used — the numbers are a
simulation built from plausible effect sizes for a comparison between an urban
street walk and a forest-healing walk.

The simulation is intentionally *plausible*, not a claim: a forest walk lowers
systolic pressure by a few mmHg and raises HRV in this generator because those
are the effect sizes the demo is meant to illustrate. Real data decides the
real answer.
"""

from __future__ import annotations

from typing import Any, Dict, List

import numpy as np
import pandas as pd

from .schema import CONDITION, FLAGS, NOTES, SOURCE, STANDARD_COLUMNS, SUBJECT, TIMESTAMP

DEFAULT_START = "2026-05-06"
DEFAULT_DAYS = 14
DEFAULT_SEED = 5020
DEFAULT_SUBJECT = "S-01"

#: Effect model (mmHg / bpm / ms) used by :func:`generate`.
EFFECTS: Dict[str, Dict[str, float]] = {
    "urban": {"walk_sbp": 2.5, "walk_dbp": 1.2, "walk_hr": 21.0, "rmssd": -3.5},
    "forest": {"walk_sbp": -8.0, "walk_dbp": -5.0, "walk_hr": 10.0, "rmssd": 6.0},
}

#: Environmental profile per condition.
ENVIRONMENT: Dict[str, Dict[str, float]] = {
    "urban": {"pm25": 27.0, "pm10": 45.0, "green_index": 0.08, "temp_c": 26.4, "humidity_pct": 52.0, "forest": 0.0},
    "forest": {"pm25": 8.5, "pm10": 16.0, "green_index": 0.84, "temp_c": 23.4, "humidity_pct": 68.0, "forest": 1.0},
}


def _schedule(day: pd.Timestamp) -> List[tuple[str, int, int]]:
    """(slot, hour, minute) for one study day — ABPM night + four daytime rests."""
    return [
        ("night", 3, 0),
        ("morning", 7, 10),
        ("walk", 10, 0),
        ("post", 11, 15),
        ("evening", 21, 40),
    ]


def generate(
    days: int = DEFAULT_DAYS,
    seed: int = DEFAULT_SEED,
    start: str = DEFAULT_START,
    *,
    include_anomalies: bool = True,
    subject: str = DEFAULT_SUBJECT,
) -> pd.DataFrame:
    """Build the standard-schema demo table.

    Days alternate ``urban`` / ``forest`` (odd days urban). Each day carries one
    nighttime ambulatory reading, a morning rest, a 40-minute walk reading, a
    post-walk rest and an evening rest, so dipping and HRV recovery can both be
    computed. Three deliberate data-quality faults are inserted when
    ``include_anomalies`` is true (a zero device reading, an inverted BP pair and
    a duplicated sync) so the cleaner has something real to report.
    """
    rng = np.random.default_rng(seed)
    start_day = pd.Timestamp(start).normalize()

    base_sbp = 133.0 + rng.normal(0, 3.0)
    base_dbp = 84.0 + rng.normal(0, 2.0)
    base_hr = 71.0 + rng.normal(0, 2.5)
    base_rmssd = 37.0 + rng.normal(0, 3.0)
    drift = 0.0
    carryover = 0.0

    rows: List[Dict[str, Any]] = []
    for day_index in range(days):
        day = start_day + pd.Timedelta(days=day_index)
        condition = "urban" if day_index % 2 == 0 else "forest"
        profile = ENVIRONMENT[condition]
        effect = EFFECTS[condition]

        drift += rng.normal(0, 0.9)
        day_noise = rng.normal(0, 1.4)
        # Weather varies day to day, more so on urban (street) days.
        weather_pm25 = max(3.0, profile["pm25"] + rng.normal(0, 6.5 if condition == "urban" else 2.6))
        weather_temp = profile["temp_c"] + rng.normal(0, 1.5)
        weather_humidity = min(95.0, max(30.0, profile["humidity_pct"] + rng.normal(0, 6.0)))
        weather_green = min(0.97, max(0.02, profile["green_index"] + rng.normal(0, 0.04)))

        for slot, hour, minute in _schedule(day):
            timestamp = day + pd.Timedelta(hours=hour, minutes=minute)
            is_night = slot == "night"

            if is_night:
                sbp = base_sbp + drift - 16.5 + rng.normal(0, 3.0) + carryover
                dbp = base_dbp + drift * 0.6 - 11.5 + rng.normal(0, 2.0) + carryover * 0.5
                hr = base_hr - 14.0 + rng.normal(0, 2.5)
                rmssd = base_rmssd * 1.24 + rng.normal(0, 3.5) + (2.0 if condition == "forest" else 0.0)
                pm25 = weather_pm25 * 0.4 + 4.0
                temp = 22.0 + rng.normal(0, 0.6)
                humidity = min(95.0, weather_humidity + 6.0)
                green = max(0.02, weather_green * 0.25)
            elif slot == "morning":
                sbp = base_sbp + drift + day_noise + carryover
                dbp = base_dbp + drift * 0.6 + day_noise * 0.5 + carryover * 0.5
                hr = base_hr + 1.0 + rng.normal(0, 2.0)
                rmssd = base_rmssd + rng.normal(0, 3.0)
                pm25 = weather_pm25
                temp = weather_temp - 1.4
                humidity = weather_humidity
                green = weather_green
            elif slot == "walk":
                sbp = base_sbp + drift + effect["walk_sbp"] + rng.normal(0, 3.5)
                dbp = base_dbp + drift * 0.6 + effect["walk_dbp"] + rng.normal(0, 2.4)
                hr = base_hr + effect["walk_hr"] + rng.normal(0, 4.0)
                rmssd = base_rmssd + effect["rmssd"] + rng.normal(0, 3.0)
                pm25 = weather_pm25
                temp = weather_temp
                humidity = weather_humidity - 4.0
                green = weather_green
            elif slot == "post":
                sbp = base_sbp + drift + effect["walk_sbp"] * 0.6 + rng.normal(0, 3.0)
                dbp = base_dbp + drift * 0.6 + effect["walk_dbp"] * 0.6 + rng.normal(0, 2.0)
                hr = base_hr + 2.0 + effect["walk_hr"] * 0.18 + rng.normal(0, 2.5)
                rmssd = base_rmssd + effect["rmssd"] * 0.9 + rng.normal(0, 3.0)
                pm25 = weather_pm25 * 0.9
                temp = weather_temp + 0.6
                humidity = weather_humidity
                green = weather_green
            else:  # evening
                sbp = base_sbp + drift * 1.1 + day_noise * 0.6 + effect["walk_sbp"] * 0.5 + rng.normal(0, 3.2)
                dbp = base_dbp + drift * 0.7 + effect["walk_dbp"] * 0.5 + rng.normal(0, 2.2)
                hr = base_hr + 2.0 + rng.normal(0, 2.2)
                rmssd = base_rmssd + effect["rmssd"] * 0.55 + rng.normal(0, 3.2)
                pm25 = weather_pm25 * 0.75
                temp = weather_temp - 2.8
                humidity = weather_humidity + 3.0
                green = weather_green

            sdnn = rmssd * 2.05 + rng.normal(0, 4.0)
            rows.append(
                {
                    TIMESTAMP: timestamp,
                    SUBJECT: subject,
                    SOURCE: "synthetic",
                    CONDITION: condition,
                    "sbp": round(float(sbp), 1),
                    "dbp": round(float(dbp), 1),
                    "hr": round(float(hr), 1),
                    "rmssd": round(float(max(8.0, rmssd)), 1),
                    "sdnn": round(float(max(12.0, sdnn)), 1),
                    "temp_c": round(float(temp), 1),
                    "humidity_pct": round(float(min(96.0, max(28.0, humidity))), 1),
                    "pm25": round(float(max(1.0, pm25)), 1),
                    "pm10": round(float(max(2.0, pm25 * 1.55 + rng.normal(0, 3.0))), 1),
                    "green_index": round(float(green), 3),
                    "forest": float(profile["forest"]),
                    "activity": slot,
                    "steps": float(int(abs(rng.normal(0, 6)) + (4200 if slot == "walk" else 0))),
                    FLAGS: None,
                    NOTES: None,
                }
            )

        # A forest day carries a small effect into the next morning.
        carryover = -2.4 * 0.6 if condition == "forest" else 0.6

    frame = pd.DataFrame(rows)[list(STANDARD_COLUMNS)]

    if include_anomalies and len(frame) >= 21:
        # 1) a device reading of zero (should be removed by the range check)
        frame.loc[frame.index[2], ["sbp", "dbp"]] = [0.0, 0.0]
        # 2) an inverted cuff pair (diastolic above systolic)
        frame.loc[frame.index[13], ["sbp", "dbp"]] = [78.0, 96.0]
        # 3) a duplicated sync one minute after the original reading
        position = min(30, len(frame) - 1)
        duplicate = frame.loc[[frame.index[position]]].copy()
        duplicate[TIMESTAMP] = duplicate[TIMESTAMP] + pd.Timedelta(minutes=1)
        duplicate[NOTES] = "duplicated sync from the same cuff session"
        frame = pd.concat([frame, duplicate], ignore_index=True)
        # 4) a few missing HRV values, as a wearable gap would leave them
        gaps = [p for p in (9, 22, 41) if p < len(frame)]
        if gaps:
            frame.loc[frame.index[gaps], ["rmssd", "sdnn"]] = np.nan

    frame = frame.sort_values(TIMESTAMP, kind="mergesort").reset_index(drop=True)
    return frame


def generate_cohort(
    subjects: int = 6,
    days: int = 8,
    seed: int = 5020,
    start: str = DEFAULT_START,
    *,
    include_anomalies: bool = False,
) -> pd.DataFrame:
    """Synthetic cohort: each participant walks both an urban and a forest day.

    Each subject is generated with its own seed (so its baseline pressure, HRV
    and drift differ), then labelled ``S-01`` … ``S-nn``. Because every subject
    appears under both conditions, the result supports a subject-level paired
    comparison — the demonstration for ``paired_subject_compare``.

    The data remain 100 % generated: no participant, vendor file or scraped
    value is used. Effect sizes are the same plausible values as :func:`generate`.
    """
    if days < 2:
        raise ValueError("a cohort needs at least two days so both conditions exist")
    frames = []
    for index in range(max(1, int(subjects))):
        frames.append(
            generate(
                days=days,
                seed=seed + 101 * index,
                start=start,
                include_anomalies=include_anomalies,
                subject=f"S-{index + 1:02d}",
            )
        )
    frame = pd.concat(frames, ignore_index=True)
    return frame.sort_values([SUBJECT, TIMESTAMP], kind="mergesort").reset_index(drop=True)


def cohort_metadata(subjects: int = 6, days: int = 8, seed: int = 5020) -> Dict[str, Any]:
    """Provenance for :func:`generate_cohort`."""
    return {
        "data": "synthetic_cohort",
        "generator": "heartmetric_core.synthetic.generate_cohort",
        "seed": seed,
        "subjects": int(subjects),
        "days": int(days),
        "note": "100% generated; every subject appears under both urban and forest conditions",
    }


def write_demo_csv(path: str = "heartmetric_demo.csv", **kwargs: Any) -> str:
    """Write the synthetic table as a CSV a user can inspect (KST timestamps)."""
    frame = generate(**kwargs)
    working = frame.copy()
    working[TIMESTAMP] = pd.to_datetime(working[TIMESTAMP]).dt.strftime("%Y-%m-%d %H:%M:%S")
    working["condition_label"] = working[CONDITION].map({"urban": "도시 가로", "forest": "산림치유"})
    working.to_csv(path, index=False, encoding="utf-8-sig")
    return path


def metadata(**kwargs: Any) -> Dict[str, Any]:
    """Provenance block attached to exported demo analyses."""
    frame = generate(**kwargs)
    return {
        "data": "synthetic",
        "generator": "heartmetric_core.synthetic.generate",
        "seed": kwargs.get("seed", DEFAULT_SEED),
        "days": kwargs.get("days", DEFAULT_DAYS),
        "start": kwargs.get("start", DEFAULT_START),
        "rows": int(len(frame)),
        "conditions": frame[CONDITION].value_counts().to_dict(),
        "note": "100% generated; no participant, vendor sample file or scraped value is used",
    }
